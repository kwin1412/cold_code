"""x86-64 cold-code backend: validation and hot-stub emission."""

from __future__ import annotations

import re
from dataclasses import dataclass

from . import ArchError


@dataclass(frozen=True)
class ArchInfo:
    name: str
    arch_id: int
    pool_alignment: int
    fast_abi_version: int
    supports_slow: bool
    supports_fast: bool
    fast_accessor: str
    cold_cflags: tuple[str, ...]


INFO = ArchInfo(
    name="x86_64",
    arch_id=1,
    pool_alignment=64,
    fast_abi_version=1,
    supports_slow=True,
    supports_fast=True,
    fast_accessor="cold_code_context_current_fast",
    cold_cflags=(
        "-ffreestanding",
        "-fPIE",
        "-fvisibility=hidden",
        "-fno-stack-protector",
        "-fno-builtin",
        "-fno-asynchronous-unwind-tables",
        "-fno-unwind-tables",
        "-fno-jump-tables",
        "-fno-ident",
        "-mno-red-zone",
        "-ffunction-sections",
        "-fcf-protection=branch",
        "-falign-functions=16",
    ),
)

ARCH_ENUM = "COLD_CODE_ARCH_X86_64"
info = INFO

RELOCATION_ALLOW = frozenset(
    {
        "R_X86_64_NONE",
        "R_X86_64_PC32",
        "R_X86_64_PLT32",
        "R_X86_64_PC64",
        "R_X86_64_PC16",
        "R_X86_64_PC8",
    }
)

_CALL_RE = re.compile(
    r"^\s*([0-9a-fA-F]+):\s+(?:callq?|jmpq?)\s+"
    r"(0x[0-9a-fA-F]+|[0-9a-fA-F]+)\s+<([^>]+)>"
)


def check_relocations(readelf_output: str) -> None:
    current_section = None
    for line in readelf_output.splitlines():
        section_match = re.match(r"Relocation section '([^']+)'", line)
        if section_match:
            current_section = section_match.group(1)
            continue
        if current_section is None or not current_section.startswith(".rela.cold_text"):
            continue
        match = re.match(r"\s*[0-9a-fA-F]+\s+[0-9a-fA-F]+\s+(R_[A-Z0-9_]+)\s+", line)
        if not match:
            continue
        kind = match.group(1)
        if kind not in RELOCATION_ALLOW:
            raise ArchError(
                f"unsupported relocation {kind} in the cold image; cold code must be "
                "position independent and self-contained (no GOT/PLT/data references)"
            )


def check_cross_slot_calls(objdump_output: str, base: int, functions: list[dict],
                           slot_size: int) -> None:
    for line in objdump_output.splitlines():
        match = _CALL_RE.match(line)
        if not match:
            continue
        insn_rel = int(match.group(1), 16) - base
        target_rel = int(match.group(2), 16) - base

        caller = None
        for fn in functions:
            if fn["offset"] <= insn_rel < fn["offset"] + fn["size"]:
                caller = fn
                break
        if caller is None:
            continue

        callee = None
        for fn in functions:
            if fn["offset"] <= target_rel < fn["offset"] + fn["size"]:
                callee = fn
                break
        if callee is None:
            raise ArchError(
                f"{caller['name']}: direct call target 0x{target_rel:x} is not a "
                "cold function; cold code must be self-contained"
            )
        if callee is caller:
            continue

        caller_slot = caller["offset"] // slot_size
        callee_slot = callee["offset"] // slot_size
        if caller_slot != callee_slot:
            raise ArchError(
                f"{caller['name']} (image slot {caller_slot}) calls "
                f"{callee['name']} (image slot {callee_slot}); cross-slot cold calls "
                "are not supported with slot-level LRU. Put them in the same slot."
            )


def emit_stubs(image_name: str, globals_: list[dict], slot_size: int, fast: bool,
               accessor: str) -> str:
    marker = f"cold_code_ram_marker_{image_name}"
    lines = [
        "/* Auto-generated by cold_code/tool/gen_cold_code.py. Do not edit. */",
    ]
    if fast:
        lines.append('#include "cold_code/abi/v1/x86_64.h"')
        lines.append("")
    lines += [
        '    .section .cold_ram,"awx",@nobits',
        "    .balign 64",
        f"    .globl {marker}",
        f"    .hidden {marker}",
        f"    .type {marker}, @object",
        f"{marker}:",
        "    .zero 1",
        f"    .size {marker}, . - {marker}",
        "",
        "    .section .text",
    ]

    for index, fn in enumerate(globals_):
        name = fn["name"]
        image_slot = fn["offset"] // slot_size
        intra = fn["offset"] % slot_size
        slow_label = f".Lcold_code_slow_{index}"

        lines += [
            "    .p2align 4",
            f"    .globl {name}",
            f"    .type {name}, @function",
            f"{name}:",
            "    .byte 0xf3,0x0f,0x1e,0xfa",  # endbr64
        ]

        if fast:
            lines += [
                f"    call {accessor}",
                "    testq %r11, %r11",
                f"    je {slow_label}",
                "    testl $COLD_CODE_FAST_STATE_READY, "
                "COLD_CODE_FAST_OFF_STATE(%r11)",
                f"    je {slow_label}",
                f"    leaq cold_code_image_{image_name}(%rip), %r10",
                "    cmpq %r10, COLD_CODE_FAST_OFF_IMAGE(%r11)",
                f"    jne {slow_label}",
                "    movq COLD_CODE_FAST_OFF_SLOT_MAP(%r11), %r10",
                f"    movl {image_slot * 4}(%r10), %r10d",
                "    testl %r10d, %r10d",
                f"    je {slow_label}",
                "    cmpl COLD_CODE_FAST_OFF_POOL_SLOTS(%r11), %r10d",
                f"    ja {slow_label}",
                "    subl $1, %r10d",
                "    pushq %rax",
                "    pushq %rcx",
                "    movq COLD_CODE_FAST_OFF_TICK(%r11), %rax",
                "    incq %rax",
                "    movq %rax, COLD_CODE_FAST_OFF_TICK(%r11)",
                "    movq COLD_CODE_FAST_OFF_WAY_USED(%r11), %rcx",
                "    movq %rax, (%rcx,%r10,8)",
                "    incq COLD_CODE_FAST_OFF_HITS(%r11)",
                f"    movl ${slot_size}, %ecx",
                "    imulq %rcx, %r10",
                "    addq COLD_CODE_FAST_OFF_POOL(%r11), %r10",
                f"    addq ${intra}, %r10",
                "    popq %rcx",
                "    popq %rax",
                "    jmp *%r10",
                f"{slow_label}:",
            ]

        lines += [
            "    pushq %rax",
            "    pushq %rdi",
            "    pushq %rsi",
            "    pushq %rdx",
            "    pushq %rcx",
            "    pushq %r8",
            "    pushq %r9",
            "    subq $128, %rsp",
        ]
        for reg in range(8):
            lines.append(f"    movdqu %xmm{reg}, {reg * 16}(%rsp)")
        lines += [
            f"    leaq cold_code_image_{image_name}(%rip), %rdi",
            f"    movl ${image_slot}, %esi",
            "    call cold_code_core_acquire_slot_v1",
            "    movq %rax, %r11",
        ]
        for reg in range(8):
            lines.append(f"    movdqu {reg * 16}(%rsp), %xmm{reg}")
        lines += [
            "    addq $128, %rsp",
            "    popq %r9",
            "    popq %r8",
            "    popq %rcx",
            "    popq %rdx",
            "    popq %rsi",
            "    popq %rdi",
            "    popq %rax",
            f"    addq ${intra}, %r11",
            "    jmp *%r11",
            f"    .size {name}, . - {name}",
            "",
        ]

    lines += ['    .section .note.GNU-stack,"",@progbits', ""]
    return "\n".join(lines)
